"""
Create a CSV containing spaCy's dependency diagnostic for the two cruise-review
sentences, plus plain-English explanations of each output column and the
specific checks used by the project's split logic.

Run in the project environment:
    python make_diagnostic_dataset.py

Requires:
    pip install spacy
    python -m spacy download en_core_web_sm

The dependency labels are generated by your installed spaCy model at runtime;
they are not hard-coded or guessed.
"""
import csv
import spacy

EXAMPLES = [
    (
        "S1",
        "I'm a solo traveler and found Cozumel very easy to navigate.",
    ),
    (
        "S2",
        "The boat ride was short and smooth, and we had plenty of time "
        "in the water without feeling rushed.",
    ),
]

SUBJECT_DEPS = {"nsubj", "nsubjpass", "csubj", "expl"}
COORDINATORS = {"and", "but", "yet"}

COLUMN_EXPLANATIONS = {
    "sentence_id": "Identifier for the example sentence (S1 or S2).",
    "sentence": "The full sentence being analyzed.",
    "token_index": "Zero-based position of this token in spaCy's token sequence.",
    "token": "The token text (usually a word or punctuation mark).",
    "dep": "spaCy dependency label: the grammatical relationship assigned to this token.",
    "head": "The token spaCy treats as this token's syntactic head.",
    "pos": "spaCy part-of-speech label, such as NOUN, VERB, or CCONJ.",
    "char_offset": "Zero-based character offset where this token starts in the sentence.",
    "is_target_coordinator": "True if the lowercase token is and, but, or yet.",
    "dep_is_cc": "True if spaCy labels this token as a coordinating conjunction (cc).",
    "head_dep": "Dependency label assigned to the token's head.",
    "head_dep_is_conj": "True if the head's dependency label is conj.",
    "head_subtree": "Text of the head's subtree, useful for seeing what the parser groups together.",
    "subject_tokens_in_head_subtree": "Tokens in the head's subtree with a subject-related dependency label used by the project code.",
    "has_subject_in_head_subtree": "True if at least one such subject-related token is present.",
    "skipped_by_coordinator_check": "True if token is not and/but/yet OR spaCy did not label it cc.",
    "skipped_by_head_check": "True if the previous check passed but the head's dependency is not conj.",
    "skipped_by_subject_check": "True if earlier checks passed but no subject-related token was found in the head subtree.",
    "skipped_by_contrast_check": "True if earlier checks passed and token is but or yet; these are handled by the separate contrast rule.",
    "would_append_boundary": "True if the token passes all checks and the code would append its character offset as a split boundary.",
    "interpretation": "Plain-English guide to reading this token's diagnostic row; it is not a human-verified grammar annotation.",
}

def main():
    try:
        nlp = spacy.load("en_core_web_sm")
    except OSError as exc:
        raise SystemExit(
            "Couldn't load spaCy model 'en_core_web_sm'. Install it with:\n"
            "  python -m spacy download en_core_web_sm\n"
            "Then rerun this script."
        ) from exc

    rows = []
    for sentence_id, sentence in EXAMPLES:
        doc = nlp(sentence)
        for token_index, token in enumerate(doc):
            target = token.lower_ in COORDINATORS
            dep_cc = token.dep_ == "cc"
            head = token.head
            head_is_conj = head.dep_ == "conj"
            subtree = list(head.subtree)
            subject_tokens = [
                t.text for t in subtree if t.dep_ in SUBJECT_DEPS
            ]
            has_subject = bool(subject_tokens)

            skip_coord = (not target) or (not dep_cc)
            skip_head = (not skip_coord) and (not head_is_conj)
            skip_subject = (
                (not skip_coord) and head_is_conj and (not has_subject)
            )
            skip_contrast = (
                (not skip_coord)
                and head_is_conj
                and has_subject
                and token.lower_ in {"but", "yet"}
            )
            append_boundary = (
                (not skip_coord)
                and head_is_conj
                and has_subject
                and token.lower_ not in {"but", "yet"}
            )

            if not target:
                interpretation = "Not one of the conjunctions this code checks."
            elif not dep_cc:
                interpretation = "Text matches a target word, but spaCy did not label it cc; the code skips it."
            elif not head_is_conj:
                interpretation = "spaCy's head is not labeled conj; the code skips it."
            elif not has_subject:
                interpretation = "No configured subject label was found in the head subtree; the code skips it."
            elif token.lower_ in {"but", "yet"}:
                interpretation = "Contrast conjunction; the code skips this here because a separate rule handles but/yet."
            else:
                interpretation = "Passes these checks; the code records this token's character offset as a candidate split boundary."

            rows.append({
                "sentence_id": sentence_id,
                "sentence": sentence,
                "token_index": token_index,
                "token": token.text,
                "dep": token.dep_,
                "head": head.text,
                "pos": token.pos_,
                "char_offset": token.idx,
                "is_target_coordinator": target,
                "dep_is_cc": dep_cc,
                "head_dep": head.dep_,
                "head_dep_is_conj": head_is_conj,
                "head_subtree": " ".join(t.text for t in subtree),
                "subject_tokens_in_head_subtree": ", ".join(subject_tokens),
                "has_subject_in_head_subtree": has_subject,
                "skipped_by_coordinator_check": skip_coord,
                "skipped_by_head_check": skip_head,
                "skipped_by_subject_check": skip_subject,
                "skipped_by_contrast_check": skip_contrast,
                "would_append_boundary": append_boundary,
                "interpretation": interpretation,
            })

    output_csv = "spacy_diagnostic_output.csv"
    with open(output_csv, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    explanation_csv = "spacy_diagnostic_column_guide.csv"
    with open(explanation_csv, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=["column", "explanation"])
        writer.writeheader()
        writer.writerows(
            {"column": column, "explanation": explanation}
            for column, explanation in COLUMN_EXPLANATIONS.items()
        )

    print(f"Wrote {output_csv} ({len(rows)} token rows)")
    print(f"Wrote {explanation_csv} ({len(COLUMN_EXPLANATIONS)} column explanations)")

if __name__ == "__main__":
    main()
